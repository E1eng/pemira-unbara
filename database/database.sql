-- =============================================
-- 3. TABEL - CANDIDATES (Paslon)
-- =============================================
CREATE TABLE IF NOT EXISTS candidates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  candidate_number int NOT NULL,
  chairman_name text NOT NULL,
  vice_chairman_name text NOT NULL DEFAULT '',
  vision text NOT NULL,
  mission text NOT NULL,
  photo_url text,
  created_at timestamptz DEFAULT now() NOT NULL
);

-- =============================================
-- 4. TABEL - VOTERS (DPT Mahasiswa)
-- =============================================
CREATE TABLE IF NOT EXISTS voters (
  nim text PRIMARY KEY,
  name text NOT NULL,
  faculty text NOT NULL DEFAULT 'Unknown',
  major text NOT NULL DEFAULT 'Unknown',
  access_code_hash text NOT NULL,
  has_voted boolean DEFAULT false NOT NULL,
  voted_at timestamptz,
  created_at timestamptz DEFAULT now() NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_voters_faculty ON voters (faculty);
CREATE INDEX IF NOT EXISTS idx_voters_has_voted ON voters (has_voted);

-- =============================================
-- 5. TABEL - RATE LIMITS (Anti Brute Force)
-- Dual key strategy:
--   'nim:<nim>'        → rate limit per akun target
--   'dev:<hash>'       → rate limit per device/IP
-- =============================================
CREATE TABLE IF NOT EXISTS vote_rate_limits (
  client_key text PRIMARY KEY,
  fail_count int DEFAULT 0 NOT NULL,
  first_fail_at timestamptz,
  blocked_until timestamptz,
  updated_at timestamptz DEFAULT now() NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_rate_limits_blocked ON vote_rate_limits (blocked_until)
  WHERE blocked_until IS NOT NULL;

-- =============================================
-- 6. TABEL - VOTES (Suara Anonim)
-- PENTING: Tidak ada kolom timestamp untuk mencegah
-- korelasi temporal dengan audit_logs (menjaga anonimitas)
-- =============================================
CREATE TABLE IF NOT EXISTS votes (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  candidate_id bigint REFERENCES candidates(id) ON DELETE CASCADE NOT NULL
);

-- =============================================
-- 7. TABEL - AUDIT LOGS
-- =============================================
CREATE TABLE IF NOT EXISTS audit_logs (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  action log_type NOT NULL,
  details jsonb,
  created_at timestamptz DEFAULT now() NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_audit_logs_action ON audit_logs (action);
CREATE INDEX IF NOT EXISTS idx_audit_logs_created ON audit_logs (created_at DESC);

-- =============================================
-- 8. TABEL - ELECTION SETTINGS
-- =============================================
CREATE TABLE IF NOT EXISTS election_settings (
  id int PRIMARY KEY DEFAULT 1,
  is_voting_open boolean DEFAULT false NOT NULL,
  show_live_result boolean DEFAULT false NOT NULL,
  updated_at timestamptz DEFAULT now() NOT NULL,
  CONSTRAINT single_row CHECK (id = 1)
);

INSERT INTO election_settings (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

-- =============================================
-- 9. TABEL - ADMIN USERS
-- =============================================
CREATE TABLE IF NOT EXISTS admin_users (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  role text DEFAULT 'admin' NOT NULL,
  created_at timestamptz DEFAULT now() NOT NULL
);

