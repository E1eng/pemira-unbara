CREATE POLICY "Admin view self" ON admin_users FOR SELECT TO authenticated USING (user_id = auth.uid());

-- RATE LIMITS (managed by SECURITY DEFINER functions only)
CREATE POLICY "System manage rate limits" ON vote_rate_limits FOR ALL USING (true) WITH CHECK (true);

-- =============================================
-- 12. FUNCTION: submit_vote (Core Voting)
-- =============================================
-- Fixes applied:
--   ✓ Dual rate limiting (per-NIM + per-device)
--   ✓ Candidate validation before INSERT
--   ✓ Anonimitas: audit log terpisah dari vote record (no shared timestamp)
--   ✓ Proper blocked_until handling in single UPSERT
-- =============================================
CREATE OR REPLACE FUNCTION submit_vote(
  p_nim text,
  p_access_code_plain text,
  p_candidate_id bigint,
  p_client_info jsonb
) RETURNS jsonb AS $$
DECLARE
  v_voter voters%ROWTYPE;
  v_settings election_settings%ROWTYPE;
  v_rate vote_rate_limits%ROWTYPE;
  v_device_key text;
  v_nim_key text;
  v_ip text;
  v_ua text;
  v_now timestamptz := now();
  v_window interval := interval '10 minutes';
  v_max_fail_device int := 10;
  v_max_fail_nim int := 5;
  v_candidate_exists boolean;
BEGIN
  -- 1. Cek voting open
  SELECT * INTO v_settings FROM election_settings WHERE id = 1;
  IF v_settings.is_voting_open IS DISTINCT FROM true THEN
    INSERT INTO audit_logs (action, details) VALUES ('LOGIN_FAIL', jsonb_build_object('reason', 'Voting Closed', 'nim', p_nim));
    RETURN jsonb_build_object('status', 'error', 'message', 'Pemilihan suara sedang ditutup.');
  END IF;

  -- 2. Build rate limit keys (DUAL: per-device AND per-NIM)
  v_ip := COALESCE(p_client_info->>'ip', 'unknown');
  v_ua := COALESCE(p_client_info->>'userAgent', 'unknown');
  v_device_key := 'dev:' || encode(digest(v_ip || '|' || v_ua, 'sha256'), 'hex');
  v_nim_key := 'nim:' || encode(digest(p_nim, 'sha256'), 'hex');

  -- 3. Rate limit check: per-device
  SELECT * INTO v_rate FROM vote_rate_limits WHERE client_key = v_device_key;
  IF FOUND AND v_rate.blocked_until > v_now THEN
    INSERT INTO audit_logs (action, details) VALUES ('SECURITY_ALERT', jsonb_build_object('reason', 'Rate Limited (Device)', 'ip', v_ip));
    RETURN jsonb_build_object('status', 'error', 'message', 'Terlalu banyak percobaan gagal. Silakan tunggu 10 menit.');
  END IF;

  -- 4. Rate limit check: per-NIM
  SELECT * INTO v_rate FROM vote_rate_limits WHERE client_key = v_nim_key;
  IF FOUND AND v_rate.blocked_until > v_now THEN
    INSERT INTO audit_logs (action, details) VALUES ('SECURITY_ALERT', jsonb_build_object('reason', 'Rate Limited (NIM)', 'nim', p_nim));
    RETURN jsonb_build_object('status', 'error', 'message', 'Akun ini terkunci sementara karena terlalu banyak percobaan gagal.');
  END IF;

  -- 5. Validate NIM (with row lock to prevent race condition)
  SELECT * INTO v_voter FROM voters WHERE nim = p_nim FOR UPDATE;
  
  IF NOT FOUND THEN
    -- Increment BOTH rate limits
    PERFORM _increment_rate_limit(v_device_key, v_max_fail_device, v_window, v_now);
    PERFORM _increment_rate_limit(v_nim_key, v_max_fail_nim, v_window, v_now);
    
    INSERT INTO audit_logs (action, details) VALUES ('LOGIN_FAIL', jsonb_build_object('reason', 'NIM Not Found', 'nim', p_nim, 'ip', v_ip));
    RETURN jsonb_build_object('status', 'error', 'message', 'NIM tidak terdaftar dalam DPT.');
  END IF;

  -- 6. Validate Token (BCrypt comparison)
  IF v_voter.access_code_hash != crypt(p_access_code_plain, v_voter.access_code_hash) THEN
    PERFORM _increment_rate_limit(v_device_key, v_max_fail_device, v_window, v_now);
    PERFORM _increment_rate_limit(v_nim_key, v_max_fail_nim, v_window, v_now);

    INSERT INTO audit_logs (action, details) VALUES ('LOGIN_FAIL', jsonb_build_object('reason', 'Wrong Token', 'nim', p_nim, 'ip', v_ip));
    RETURN jsonb_build_object('status', 'error', 'message', 'Kode Akses salah.');
  END IF;

  -- 7. Check already voted
  IF v_voter.has_voted THEN
    INSERT INTO audit_logs (action, details) VALUES ('LOGIN_FAIL', jsonb_build_object('reason', 'Already Voted', 'nim', p_nim, 'ip', v_ip));
    RETURN jsonb_build_object('status', 'error', 'message', 'Mahasiswa ini sudah menggunakan hak pilihnya.');
  END IF;

  -- 8. Validate candidate exists
  SELECT EXISTS (SELECT 1 FROM candidates WHERE id = p_candidate_id) INTO v_candidate_exists;
  IF NOT v_candidate_exists THEN
    RETURN jsonb_build_object('status', 'error', 'message', 'Kandidat tidak valid.');
  END IF;

  -- 9. SUCCESS: Record vote (anonymously - no timestamp in votes table)
  DELETE FROM vote_rate_limits WHERE client_key IN (v_device_key, v_nim_key);
  UPDATE voters SET has_voted = true, voted_at = v_now WHERE nim = p_nim;
  INSERT INTO votes (candidate_id) VALUES (p_candidate_id);

  -- 10. Audit log (hanya fakultas, tanpa NIM untuk privasi tambahan)
  INSERT INTO audit_logs (action, details) 
  VALUES ('VOTE_SUCCESS', jsonb_build_object('faculty', v_voter.faculty, 'ip', v_ip));

  RETURN jsonb_build_object('status', 'success', 'message', 'Suara berhasil direkam. Terima kasih!');
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, extensions;

-- =============================================
-- 13. HELPER: _increment_rate_limit (internal)
-- =============================================
CREATE OR REPLACE FUNCTION _increment_rate_limit(
  p_key text,
  p_max_fail int,
  p_window interval,
  p_now timestamptz
) RETURNS void AS $$
BEGIN
  INSERT INTO vote_rate_limits (client_key, fail_count, first_fail_at, updated_at, blocked_until)
  VALUES (p_key, 1, p_now, p_now, NULL)
  ON CONFLICT (client_key) DO UPDATE
  SET 
    fail_count = vote_rate_limits.fail_count + 1,
    updated_at = p_now,
    blocked_until = CASE 
      WHEN (vote_rate_limits.fail_count + 1) >= p_max_fail THEN p_now + p_window
      ELSE vote_rate_limits.blocked_until
    END;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

-- =============================================
-- 14. FUNCTION: validate_voter (Pre-login Check)
-- =============================================
-- Fixes applied:
--   ✓ FOUND variable saved before UPSERT overwrites it
--   ✓ Dual rate limiting (per-NIM + per-device)
--   ✓ Proper error differentiation (NIM not found vs wrong token)
-- =============================================
CREATE OR REPLACE FUNCTION validate_voter(
  p_nim text,
  p_access_code_plain text,
  p_client_info jsonb DEFAULT '{}'::jsonb
) RETURNS jsonb AS $$
DECLARE
  v_voter voters%ROWTYPE;
  v_rate vote_rate_limits%ROWTYPE;
  v_device_key text;
  v_nim_key text;
  v_ip text;
  v_ua text;
  v_now timestamptz := now();
  v_window interval := interval '10 minutes';
  v_max_fail_device int := 10;
  v_max_fail_nim int := 5;
  v_voter_found boolean;
BEGIN
  -- Build rate limit keys
  v_ip := COALESCE(p_client_info->>'ip', 'unknown');
  v_ua := COALESCE(p_client_info->>'userAgent', 'unknown');
  v_device_key := 'dev:' || encode(digest(v_ip || '|' || v_ua, 'sha256'), 'hex');
  v_nim_key := 'nim:' || encode(digest(p_nim, 'sha256'), 'hex');

  -- 1. Check if device is blocked
  SELECT * INTO v_rate FROM vote_rate_limits WHERE client_key = v_device_key;
  IF FOUND AND v_rate.blocked_until > v_now THEN
    INSERT INTO audit_logs (action, details) VALUES ('SECURITY_ALERT', jsonb_build_object('reason', 'Rate Limited (Device)', 'ip', v_ip));
    RETURN jsonb_build_object('ok', false, 'reason', 'Terlalu banyak percobaan. Tunggu 10 menit.');
  END IF;

  -- 2. Check if NIM is blocked
  SELECT * INTO v_rate FROM vote_rate_limits WHERE client_key = v_nim_key;
  IF FOUND AND v_rate.blocked_until > v_now THEN
    INSERT INTO audit_logs (action, details) VALUES ('SECURITY_ALERT', jsonb_build_object('reason', 'Rate Limited (NIM)', 'nim', p_nim));
    RETURN jsonb_build_object('ok', false, 'reason', 'Akun terkunci sementara. Tunggu 10 menit.');
  END IF;

  -- 3. Validate NIM
  SELECT * INTO v_voter FROM voters WHERE nim = p_nim;
  v_voter_found := FOUND;
  
  -- 4. If NIM not found OR Token mismatch → increment both rate limits
  IF NOT v_voter_found OR v_voter.access_code_hash != crypt(p_access_code_plain, v_voter.access_code_hash) THEN
    PERFORM _increment_rate_limit(v_device_key, v_max_fail_device, v_window, v_now);
    PERFORM _increment_rate_limit(v_nim_key, v_max_fail_nim, v_window, v_now);

    -- Log specific error
    IF NOT v_voter_found THEN
      INSERT INTO audit_logs (action, details) VALUES ('LOGIN_FAIL', jsonb_build_object('reason', 'NIM Not Found', 'nim', p_nim, 'ip', v_ip));
      RETURN jsonb_build_object('ok', false, 'reason', 'NIM tidak ditemukan.');
    ELSE
      INSERT INTO audit_logs (action, details) VALUES ('LOGIN_FAIL', jsonb_build_object('reason', 'Wrong Token', 'nim', p_nim, 'ip', v_ip));
      RETURN jsonb_build_object('ok', false, 'reason', 'Kode Akses salah.');
    END IF;
  END IF;
  
  -- 5. Success: Reset rate limits for this client
  DELETE FROM vote_rate_limits WHERE client_key IN (v_device_key, v_nim_key);

  RETURN jsonb_build_object(
    'ok', true, 
    'has_voted', v_voter.has_voted, 
    'name', v_voter.name,
    'faculty', v_voter.faculty
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, extensions;

-- =============================================
-- 15. FUNCTION: admin_add_voter (Import DPT)
-- =============================================
CREATE OR REPLACE FUNCTION admin_add_voter(
  p_nim text,
  p_name text,
  p_faculty text,
  p_major text,
  p_access_code_plain text
) RETURNS void AS $$
BEGIN
  -- Defense-in-depth: fungsi ini SECURITY DEFINER (bypass RLS),
  -- jadi pastikan caller benar-benar admin meski sudah dibatasi GRANT.
  IF NOT is_admin() THEN
    RAISE EXCEPTION 'Unauthorized: admin only';
  END IF;

  INSERT INTO voters (nim, name, faculty, major, access_code_hash)
  VALUES (
    p_nim,
    p_name,
    COALESCE(NULLIF(p_faculty, ''), 'Unknown'),
    COALESCE(NULLIF(p_major, ''), 'Unknown'),
    crypt(p_access_code_plain, gen_salt('bf'))
  )
  ON CONFLICT (nim) DO UPDATE
  SET name = EXCLUDED.name,
      faculty = EXCLUDED.faculty,
      major = EXCLUDED.major,
      access_code_hash = EXCLUDED.access_code_hash;
      
  INSERT INTO audit_logs (action, details) VALUES ('ADMIN_ACTION', jsonb_build_object('type', 'UPSERT_VOTER', 'nim', p_nim));
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, extensions;

-- =============================================
-- 16. FUNCTION: get_vote_recap (Real Count)
-- =============================================
-- Enforces show_live_result at DB level (not just frontend)
-- Admin always sees real data regardless of setting
-- =============================================
CREATE OR REPLACE FUNCTION get_vote_recap()
RETURNS TABLE (
  candidate_id bigint, 
  candidate_number int,
  chairman_name text,
  vice_chairman_name text,
  photo_url text,
  total_votes bigint
) AS $$
DECLARE
  v_show_live boolean;
  v_is_admin boolean;
BEGIN
  -- Check if caller is admin
  v_is_admin := EXISTS (SELECT 1 FROM admin_users WHERE user_id = auth.uid());

  -- Non-admin: enforce show_live_result setting
  IF NOT v_is_admin THEN
    SELECT es.show_live_result INTO v_show_live FROM election_settings es WHERE es.id = 1;
    IF v_show_live IS DISTINCT FROM true THEN
      RETURN QUERY
      SELECT c.id, c.candidate_number, c.chairman_name, c.vice_chairman_name, c.photo_url, 0::bigint AS total_votes
      FROM candidates c
      ORDER BY c.candidate_number;
      RETURN;
    END IF;
  END IF;

  RETURN QUERY
  SELECT 
    c.id,
    c.candidate_number,
    c.chairman_name,
    c.vice_chairman_name,
    c.photo_url,
    count(v.id)::bigint AS total_votes
  FROM candidates c
  LEFT JOIN votes v ON c.id = v.candidate_id
  GROUP BY c.id, c.candidate_number, c.chairman_name, c.vice_chairman_name, c.photo_url
  ORDER BY total_votes DESC;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

-- =============================================
-- 17. FUNCTION: get_participation_stats
-- =============================================
CREATE OR REPLACE FUNCTION get_participation_stats()
RETURNS TABLE (
  faculty text,
  total_voters bigint,
  already_voted bigint,
  participation_percentage numeric
) AS $$
BEGIN
  -- Defense-in-depth: hanya admin yang boleh melihat statistik partisipasi.
  IF NOT is_admin() THEN
    RAISE EXCEPTION 'Unauthorized: admin only';
  END IF;

  RETURN QUERY
  SELECT
    v.faculty,
    count(*)::bigint AS total_voters,
    count(CASE WHEN v.has_voted THEN 1 END)::bigint AS already_voted,
    round((count(CASE WHEN v.has_voted THEN 1 END)::numeric / NULLIF(count(*)::numeric, 0)) * 100, 2) AS participation_percentage
  FROM voters v
  GROUP BY v.faculty
  ORDER BY participation_percentage DESC;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

